export const SITE_THEME_PRESET_IDS = SITE_PALETTE_DEFINITIONS.map(
  (palette) => palette.id,
) as unknown as [
  (typeof SITE_PALETTE_DEFINITIONS)[number]["id"],
  ...(typeof SITE_PALETTE_DEFINITIONS)[number]["id"][],
];

export type SiteThemePresetId = (typeof SITE_PALETTE_DEFINITIONS)[number]["id"];

export const SITE_PALETTE_BY_ID: Record<
  SiteThemePresetId,
  (typeof SITE_PALETTE_DEFINITIONS)[number]
> = Object.fromEntries(
  SITE_PALETTE_DEFINITIONS.map((palette) => [palette.id, palette]),
) as Record<SiteThemePresetId, (typeof SITE_PALETTE_DEFINITIONS)[number]>;

export function getPaletteDefinition(
  id: SiteThemePresetId,
): (typeof SITE_PALETTE_DEFINITIONS)[number] {
  return SITE_PALETTE_BY_ID[id];
}

export function resolvePaletteCssTokens(
  id: SiteThemePresetId,
): SitePaletteCssTokens {
  return SITE_PALETTE_BY_ID[id].tokens;
}

export function isSiteThemePresetId(value: string): value is SiteThemePresetId {
  return Object.prototype.hasOwnProperty.call(SITE_PALETTE_BY_ID, value);
}

/** Emit a static CSS custom-property block for a palette (tests / docs). */
export function formatPaletteCssBlock(
  id: SiteThemePresetId,
  selector: string,
): string {
  const tokens = resolvePaletteCssTokens(id);
  const lines = Object.entries(CSS_TOKEN_VAR_NAMES).map(([key, cssVar]) => {
    const value = tokens[key as keyof SitePaletteCssTokens];
    return `  ${cssVar}: ${value};`;
  });
  return `${selector} {\n${lines.join("\n")}\n}`;
}
